-- Признак «сервисная заявка» — мелкая доделка/переделка по уже сданному объекту,
-- а НЕ полноценный монтаж. Такие заявки идут по той же воронке (у них есть статус),
-- но в интерфейсе выносятся в отдельную вкладку «Сервис» и не мешаются в «Монтажах».
-- Именно флаг, а не отдельный status: сервисная заявка тоже проходит стадии
-- (назначена/выполнена/оплачена), поэтому статус остаётся прежним механизмом.
ALTER TABLE t_p45929761_bold_move_project.live_chats
  ADD COLUMN IF NOT EXISTS is_service BOOLEAN NOT NULL DEFAULT FALSE;

-- Индекс — вкладка «Сервис» и исключение сервисных из «Монтажей» фильтруют по этому полю
CREATE INDEX IF NOT EXISTS idx_live_chats_is_service
  ON t_p45929761_bold_move_project.live_chats (company_id, is_service);
